/// Transport boundary: caller supplies approved content; this library does not inspect app data.
public struct PlanImage: Sendable, Equatable {
    public enum Format: String, Sendable { case jpeg, png, webp
        var mimeType: String { "image/\(rawValue)" }
    }
    public let bytes: Data
    public let format: Format
    public init(bytes: Data, format: Format) throws {
        guard !bytes.isEmpty, bytes.count <= 10_000_000 else { throw PlanError.invalidInput }
        // Never forward caller-supplied image bytes: their container may contain
        // EXIF GPS, XMP, thumbnails or other private metadata. Re-encode pixels.
        #if canImport(ImageIO) && canImport(CoreGraphics)
        let normalized = try PlanImageSanitizer.reencode(bytes: bytes, format: format)
        self.bytes = normalized.bytes
        self.format = normalized.format
        #else
        // The library targets Apple platforms. Fail closed elsewhere rather
        // than silently forwarding unmodified image metadata.
        throw PlanError.unsupportedPlatform
        #endif
    }
}

#if canImport(ImageIO) && canImport(CoreGraphics)
/// ImageIO decodes pixels and writes a new container with no source metadata.
/// Maximum dimension also avoids large raw bitmap allocations.
internal enum PlanImageSanitizer {
    static func reencode(bytes: Data, format: PlanImage.Format) throws ->
        (bytes: Data, format: PlanImage.Format) {
        guard let source = CGImageSourceCreateWithData(bytes as CFData, nil),
              CGImageSourceGetCount(source) > 0 else { throw PlanError.invalidInput }
        // WebP may be supported for decoding, but ImageIO output is normalized
        // to PNG; do not pretend newly generated bytes are still WebP.
        let outputFormat: PlanImage.Format = format == .webp ? .png : format
        let outputType = outputFormat == .jpeg ? "public.jpeg" : "public.png"
        for maxDimension in [1280, 960, 720] {
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: maxDimension,
                kCGImageSourceShouldCache: false,
            ]
            guard let pixels = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
            else { throw PlanError.invalidInput }
            let output = NSMutableData()
            guard let destination = CGImageDestinationCreateWithData(
                output as CFMutableData, outputType as CFString, 1, nil) else { throw PlanError.invalidInput }
            let encoding: [CFString: Any] = outputFormat == .jpeg ?
                [kCGImageDestinationLossyCompressionQuality: 0.82] : [:]
            CGImageDestinationAddImage(destination, pixels, encoding as CFDictionary)
            guard CGImageDestinationFinalize(destination) else { throw PlanError.invalidInput }
            let clean = output as Data
            if !clean.isEmpty && clean.count <= 4_000_000 {
                return (clean, outputFormat)
            }
        }
        throw PlanError.invalidInput
    }
}
#endif

public struct PlanMessage: Sendable, Equatable {
    public enum Role: String, Sendable { case user, assistant }
    public let role: Role
    public let text: String
    public let images: [PlanImage]
    public init(role: Role, text: String, images: [PlanImage] = []) throws {
        guard text.utf8.count <= 500_000, images.count <= 4,
              !(text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && images.isEmpty),
              role == .user || images.isEmpty else { throw PlanError.invalidInput }
        self.role = role
        self.text = text
        self.images = images
    }
}

