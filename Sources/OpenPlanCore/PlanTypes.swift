    public let text: String
    public let model: String
    public init(text: String, model: String) { self.text = text; self.model = model }
}

/// Safe protocol and transport classifications. Never includes request contents or credentials.
public enum PlanStreamIssue: String, Sendable, Equatable {
    case unexpectedContentType = "unexpected_content_type"
    case missingCompletion = "missing_completion"
    case emptyCompletedResponse = "empty_completed_response"
    case malformedEvent = "malformed_event"
    case timedOut = "timed_out"
    case offline = "network_offline"
    case transportFailed = "transport_failed"
}

/// Only safe, bounded request metadata. Never includes URL query, content or bearer token.
public struct PlanResponseDiagnostic: Sendable, Equatable {
    public let model: String
    public let httpStatus: Int?
    public let responseKind: String
    public let requestID: String?
    public init(model: String, httpStatus: Int?, responseKind: String, requestID: String?) {
        self.model = model
        self.httpStatus = httpStatus
        self.responseKind = responseKind
        self.requestID = requestID
    }
}

/// These errors are deliberately independent of authentication server response bodies.
public enum PlanError: Error, Equatable, LocalizedError {
    case unsupportedPlatform, invalidInput, notConnected, permissionMissing
    case invalidState, invalidCallback, expiredSignIn, invalidIdentity
    case invalidToken, authorizationFailed, requestFailed(Int), responseRejected(Int, String?), serviceUnavailable
    case usageUnavailable, noAvailableModels, incompleteResponse, responseInterrupted
    case cancelled, disabledUntilApproved, streamIssue(PlanStreamIssue)

    public var errorDescription: String? {
        switch self {
        case .unsupportedPlatform: return "This operating system is not supported."
        case .invalidInput: return "The selected input is not valid."
        case .notConnected: return "Connect a ChatGPT account first."
        case .permissionMissing: return "ChatGPT plan access was not authorized."
        case .invalidState, .invalidCallback, .expiredSignIn, .invalidIdentity, .invalidToken:
            return "ChatGPT sign-in could not be verified. Please try again."
        case .authorizationFailed: return "ChatGPT authorization was not completed."
        case .requestFailed(let status): return "The AI service returned HTTP \(status)."
        case .responseRejected(let status, let code):
            let statusText = status >= 400 ? "HTTP \(status)" : "stream"
            return "ChatGPT rejected the \(statusText) request" + (code.map { " (\($0))" } ?? "") + "."
        case .serviceUnavailable: return "The AI service could not complete this request."
        case .usageUnavailable: return "ChatGPT plan usage is currently unavailable."
        case .noAvailableModels: return "No ChatGPT models are available for this connected account."
        case .incompleteResponse, .responseInterrupted: return "The AI response did not finish."
        case .cancelled: return "The request was cancelled."
        case .streamIssue(let kind): return "ChatGPT transport diagnostic: \(kind.rawValue)."
        case .disabledUntilApproved: return "This integration has not been enabled for this application."
        }
    }
}
